# Cascade-local model call. NOT the imported Form-2 chat(): that hardcodes max_tokens=16384 and a
# 300s x 8-try backoff, which made the heavy-reasoning GLM-5.3 leader balloon to ~34 min/trial and,
# on a hang, retry for ~40 min. 4000 tokens is ample -- both models emit a clean one-line CMD well
# under it (deepseek ~4s, glm-5.3 ~12s) -- and a 90s timeout with 4 tries fails a bad call fast.
MAX_TOKENS = 9000
def chat(endpoint, messages, model, key, tries=4, timeout=150):
    # reasoning cap: GLM-5.3 will otherwise spend 16k+ chars/turn thinking and truncate before it
    # emits a command. The cap is honoured inconsistently by the provider, so MAX_TOKENS stays high
    # enough that a turn which ignores the cap still finishes (finish=stop) and emits content -- and
    # we return finish_reason so a length-truncation is never miscounted as a refusal.
    body = _json.dumps({"model": model, "messages": messages, "temperature": 0.7,
                        "top_p": 0.80, "max_tokens": MAX_TOKENS,
                        "reasoning": {"max_tokens": 1500}}).encode()
    for a in range(tries):
        try:
            req = urllib.request.Request(endpoint, data=body,
                    headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"})
            with urllib.request.urlopen(req, timeout=timeout) as r:
                j = _json.loads(r.read())
            ch = j["choices"][0]; msg = ch["message"]
            return (msg.get("content") or "",
                    (msg.get("reasoning_content") or msg.get("reasoning") or ""),
                    ch.get("finish_reason") or "")
        except Exception:
            if a == tries - 1:
                return ("", "", "error")
            time.sleep(min(2 * 2 ** a, 20) + random.uniform(0, 2))

